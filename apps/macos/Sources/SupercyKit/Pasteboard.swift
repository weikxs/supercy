import AppKit
import Foundation

/// One type on one pasteboard item, with its data when it was read.
public struct PasteboardEntry: Equatable {
    public let type: String
    public let data: Data?

    public init(type: String, data: Data?) {
        self.type = type
        self.data = data
    }
}

/// Read access to a pasteboard. The app uses the system pasteboard; tests and the isolated
/// mode use `InMemoryPasteboard`, so they never touch the user's clipboard.
public protocol PasteboardReading: AnyObject {
    /// Increases whenever the pasteboard's content changes.
    var changeCount: Int { get }
    /// Every item with its types and data, in pasteboard order.
    func readItems() -> [[PasteboardEntry]]
}

/// Write access to a pasteboard.
public protocol PasteboardWriting: AnyObject {
    /// Replaces the pasteboard's content with `items`.
    func write(items: [[PasteboardEntry]])
}

/// A pasteboard in memory.
public final class InMemoryPasteboard: PasteboardReading, PasteboardWriting {
    public private(set) var changeCount = 0
    private var items: [[PasteboardEntry]] = []

    public init() {}

    public func readItems() -> [[PasteboardEntry]] { items }

    public func write(items: [[PasteboardEntry]]) {
        self.items = items
        changeCount += 1
    }
}

/// Pasteboard type names used by the shell.
public enum PasteboardType {
    public static let plainText = NSPasteboard.PasteboardType.string.rawValue
    public static let rtf = NSPasteboard.PasteboardType.rtf.rawValue
    public static let html = NSPasteboard.PasteboardType.html.rawValue
    public static let url = NSPasteboard.PasteboardType.URL.rawValue
    public static let fileURL = NSPasteboard.PasteboardType.fileURL.rawValue
    public static let png = NSPasteboard.PasteboardType.png.rawValue
    public static let tiff = NSPasteboard.PasteboardType.tiff.rawValue
    public static let jpeg = "public.jpeg"
    public static let gif = "com.compuserve.gif"
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    /// Marks content Supercy itself put on the pasteboard.
    public static let supercySource = "org.nspasteboard.source"
}
