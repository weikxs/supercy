/// One form of an item to put back on the clipboard, in paste-preference order.
#[derive(Clone, Debug, PartialEq, Eq, uniffi::Enum)]
pub enum PasteRepresentation {
    /// Plain text.
    PlainText {
        /// The text.
        text: String,
    },
    /// Rich text; `plain` is for plain-text paste.
    RichText {
        /// RTF source.
        rtf: Option<Vec<u8>>,
        /// HTML source.
        html: Option<String>,
        /// Plain-text form.
        plain: String,
    },
    /// A link.
    Url {
        /// The URL.
        url: String,
        /// Its title, if known.
        title: Option<String>,
    },
    /// An image.
    Image {
        /// Encoding.
        format: ImageFormat,
        /// Width in pixels (0 if unknown).
        width: u32,
        /// Height in pixels (0 if unknown).
        height: u32,
        /// The encoded image.
        bytes: Vec<u8>,
    },
    /// Copied files, by name.
    FileRef {
        /// File names.
        names: Vec<String>,
    },
}

impl From<model::Representation> for PasteRepresentation {
    fn from(rep: model::Representation) -> Self {
        let text = |s: &model::SecretString| s.expose().to_owned();
        match rep {
            model::Representation::PlainText(t) => Self::PlainText { text: text(&t) },
            model::Representation::RichText { rtf, html, plain } => Self::RichText {
                rtf: rtf.map(|bytes| bytes.expose().to_vec()),
                html: html.as_ref().map(text),
                plain: text(&plain),
            },
            model::Representation::Url { url, title } => Self::Url {
                url: text(&url),
                title: title.as_ref().map(text),
            },
            model::Representation::Image {
                format,
                width,
                height,
                bytes,
            } => Self::Image {
                format: format.into(),
                width,
                height,
                bytes: bytes.expose().to_vec(),
            },
            model::Representation::FileRef { names } => Self::FileRef { names },
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn character_ranges_become_utf16_ranges() {
        let ranges = utf16_ranges("a😀b会c", &[(0, 1), (1, 2), (2, 4), (9, 12)]);

        assert_eq!(
            ranges,
            vec![
                TextRange {
                    location: 0,
                    length: 1
                },
                TextRange {
                    location: 1,
                    length: 2
                },
                TextRange {
                    location: 3,
                    length: 2
                },
            ]
        );
    }
}
