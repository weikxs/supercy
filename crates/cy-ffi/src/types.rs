/// One form of an item to put back on the clipboard, in paste-preference order.
#[derive(Clone, Debug, PartialEq, Eq, uniffi::Enum)]
pub enum PasteRepresentation {
    /// Plain text.
    PlainText {
        /// The text.
        text: String,
    },
    /// Rich text; `plain` is for plain-text paste.
    RichText {
        /// RTF source.
        rtf: Option<Vec<u8>>,
        /// HTML source.
        html: Option<String>,
        /// Plain-text form.
        plain: String,
    },
    /// A link.
    Url {
        /// The URL.
        url: String,
        /// Its title, if known.
        title: Option<String>,
    },
    /// An image.
    Image {
        /// Encoding.
        format: ImageFormat,
        /// Width in pixels (0 if unknown).
        width: u32,
        /// Height in pixels (0 if unknown).
        height: u32,
        /// The encoded image.
        bytes: Vec<u8>,
    },
    /// Copied files, by name.
    FileRef {
        /// File names.
        names: Vec<String>,
    },
}

impl From<model::Representation> for PasteRepresentation {
    fn from(rep: model::Representation) -> Self {
        let text = |s: &model::SecretString| s.expose().to_owned();
        match rep {
            model::Representation::PlainText(t) => Self::PlainText { text: text(&t) },
            model::Representation::RichText { rtf, html, plain } => Self::RichText {
                rtf: rtf.map(|bytes| bytes.expose().to_vec()),
                html: html.as_ref().map(text),
                plain: text(&plain),
            },
            model::Representation::Url { url, title } => Self::Url {
                url: text(&url),
                title: title.as_ref().map(text),
            },
            model::Representation::Image {
                format,
                width,
                height,
                bytes,
            } => Self::Image {
                format: format.into(),
                width,
                height,
                bytes: bytes.expose().to_vec(),
            },
            model::Representation::FileRef { names } => Self::FileRef { names },
        }
    }
}

/// What Supercy keeps and for how long. Ranges are checked by `update_settings`.
#[derive(Clone, Debug, PartialEq, Eq, uniffi::Record)]
pub struct Settings {
    /// Unpinned items kept (50–10 000).
    pub max_items: u32,
    /// Longest text kept, in bytes (1 KiB–2 MiB).
    pub max_text_bytes: u32,
    /// Largest image kept, in bytes (64 KiB–8 MiB).
    pub max_image_bytes: u32,
    /// All unpinned images together, in bytes (1 MiB–1 GiB).
    pub max_image_total_bytes: u64,
    /// Whether sensitive content is detected and expired.
    pub detect_sensitive: bool,
    /// Lifetime of sensitive items in milliseconds (10 s–24 h).
    pub sensitive_ttl_ms: u64,
    /// Whether content marked auto-generated is kept.
    pub keep_auto_generated: bool,
    /// Apps whose copies are never kept, by bundle identifier.
    pub ignored_apps: Vec<String>,
}

impl From<cy_engine::Settings> for Settings {
    fn from(s: cy_engine::Settings) -> Self {
        Self {
            max_items: s.max_items,
            max_text_bytes: s.max_text_bytes,
            max_image_bytes: s.max_image_bytes,
            max_image_total_bytes: s.max_image_total_bytes,
            detect_sensitive: s.detect_sensitive,
            sensitive_ttl_ms: s.sensitive_ttl_ms,
            keep_auto_generated: s.keep_auto_generated,
            ignored_apps: s.ignored_apps,
        }
    }
}

impl From<Settings> for cy_engine::Settings {
    fn from(s: Settings) -> Self {
        Self {
            max_items: s.max_items,
            max_text_bytes: s.max_text_bytes,
            max_image_bytes: s.max_image_bytes,
            max_image_total_bytes: s.max_image_total_bytes,
            detect_sensitive: s.detect_sensitive,
            sensitive_ttl_ms: s.sensitive_ttl_ms,
            keep_auto_generated: s.keep_auto_generated,
            ignored_apps: s.ignored_apps,
        }
    }
}
