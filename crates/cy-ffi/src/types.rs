//! Records and enums that cross the boundary, and their conversions to the core's types.

use cy_model as model;

/// The kind of an item's primary content.
#[derive(Clone, Copy, Debug, PartialEq, Eq, uniffi::Enum)]
pub enum ItemKind {
    /// Plain text.
    Text,
    /// Rich text (RTF or HTML) with a plain-text form.
    RichText,
    /// A link.
    Url,
    /// An image.
    Image,
    /// References to copied files.
    FileRef,
}

impl From<model::RepKind> for ItemKind {
    fn from(kind: model::RepKind) -> Self {
        match kind {
            model::RepKind::Text => Self::Text,
            model::RepKind::RichText => Self::RichText,
            model::RepKind::Url => Self::Url,
            model::RepKind::Image => Self::Image,
            model::RepKind::FileRef => Self::FileRef,
        }
    }
}

impl From<ItemKind> for model::RepKind {
    fn from(kind: ItemKind) -> Self {
        match kind {
            ItemKind::Text => Self::Text,
            ItemKind::RichText => Self::RichText,
            ItemKind::Url => Self::Url,
            ItemKind::Image => Self::Image,
            ItemKind::FileRef => Self::FileRef,
        }
    }
}

/// How search terms match.
#[derive(Clone, Copy, Debug, PartialEq, Eq, uniffi::Enum)]
pub enum SearchMode {
    /// Characters in order with gaps; pinyin included.
    Fuzzy,
    /// Substring of the text.
    Exact,
}

impl From<SearchMode> for cy_engine::MatchMode {
    fn from(mode: SearchMode) -> Self {
        match mode {
            SearchMode::Fuzzy => Self::Fuzzy,
            SearchMode::Exact => Self::Exact,
        }
    }
}

/// The application in front when something was copied.
#[derive(Clone, Debug, PartialEq, Eq, uniffi::Record)]
pub struct SourceApp {
    /// Bundle identifier, such as `com.example.editor`.
    pub bundle_id: String,
    /// Display name.
    pub name: String,
}

impl From<SourceApp> for model::SourceApp {
    fn from(app: SourceApp) -> Self {
        Self {
            bundle_id: app.bundle_id,
            name: app.name,
        }
    }
}

/// One type on the clipboard. Text types are passed as UTF-8. `data` is `nil` for markers and
/// for types larger than the shell reads; `size` is then their size.
#[derive(Clone, Debug, PartialEq, Eq, uniffi::Record)]
pub struct ClipEntry {
    /// The platform's type name, such as `public.utf8-plain-text`.
    pub type_id: String,
    /// The data, if read.
    pub data: Option<Vec<u8>>,
    /// Size of the data in bytes.
    pub size: u64,
}

/// The clipboard at one change.
#[derive(Clone, Debug, PartialEq, Eq, uniffi::Record)]
pub struct ClipboardSnapshot {
    /// Every type on the clipboard.
    pub entries: Vec<ClipEntry>,
    /// The application in front.
    pub front_app: Option<SourceApp>,
    /// When the change was seen, in milliseconds since 1970.
    pub captured_at_ms: u64,
}

impl From<ClipboardSnapshot> for model::ClipboardSnapshot {
    fn from(snapshot: ClipboardSnapshot) -> Self {
        let entries = snapshot
            .entries
            .into_iter()
            .map(|entry| model::ClipEntry {
                type_id: entry.type_id,
                data: entry.data.map(model::SecretBytes::new),
                size: entry.size,
            })
            .collect();
        Self {
            entries,
            front_app: snapshot.front_app.map(Into::into),
            captured_at_ms: snapshot.captured_at_ms,
        }
    }
}

/// Why a copy was not kept.
#[derive(Clone, Copy, Debug, PartialEq, Eq, uniffi::Enum)]
pub enum DropReason {
    /// Marked concealed (a password) by the source app.
    Concealed,
    /// Marked transient by the source app.
    Transient,
    /// Marked auto-generated.
    AutoGenerated,
    /// Copied from an ignored app.
    IgnoredApp,
    /// Copied files (not recorded yet).
    Files,
    /// Nothing Supercy can keep.
    Unsupported,
    /// Larger than the limits.
    TooLarge,
}

impl From<cy_engine::DropReason> for DropReason {
    fn from(reason: cy_engine::DropReason) -> Self {
        use cy_engine::DropReason as R;
        match reason {
            R::Concealed => Self::Concealed,
            R::Transient => Self::Transient,
            R::AutoGenerated => Self::AutoGenerated,
            R::IgnoredApp => Self::IgnoredApp,
            R::Files => Self::Files,
            R::Unsupported => Self::Unsupported,
            R::TooLarge => Self::TooLarge,
        }
    }
}

/// What happened to a snapshot.
#[derive(Clone, Debug, PartialEq, Eq, uniffi::Enum)]
pub enum IngestOutcome {
    /// A new item; `evicted` items were removed by the limits.
    Stored {
        /// The new item's id.
        id: String,
        /// Ids removed by the limits.
        evicted: Vec<String>,
    },
    /// The content was already there; that item moved to the top.
    Updated {
        /// The item's id.
        id: String,
    },
    /// Nothing was kept.
    Dropped {
        /// Why.
        reason: DropReason,
    },
}

/// The result of `ingest`.
#[derive(Clone, Debug, PartialEq, Eq, uniffi::Record)]
pub struct IngestResult {
    /// What happened.
    pub outcome: IngestOutcome,
    /// When to call `tick` next, if ever (milliseconds since 1970). Schedule one timer for it.
    pub next_tick_ms: Option<u64>,
}

impl From<cy_engine::IngestReport> for IngestResult {
    fn from(report: cy_engine::IngestReport) -> Self {
        let outcome = match report.outcome {
            cy_engine::IngestOutcome::Stored { id, evicted } => IngestOutcome::Stored {
                id: id.to_string(),
                evicted: evicted.iter().map(ToString::to_string).collect(),
            },
            cy_engine::IngestOutcome::Updated { id } => {
                IngestOutcome::Updated { id: id.to_string() }
            }
            cy_engine::IngestOutcome::Dropped { reason } => IngestOutcome::Dropped {
                reason: reason.into(),
            },
        };
        Self {
            outcome,
            next_tick_ms: report.next_expiry_ms,
        }
    }
}

/// An item as lists show it: a short preview, never the full content.
#[derive(Clone, Debug, PartialEq, Eq, uniffi::Record)]
pub struct ItemSummary {
    /// Id, 32 hexadecimal digits.
    pub id: String,
    /// Kind of the primary content.
    pub kind: ItemKind,
    /// The first 300 characters of the text; empty for images.
    pub preview: String,
    /// Whether it is pinned.
    pub pinned: bool,
    /// Last copy or paste, in milliseconds since 1970.
    pub last_used_ms: u64,
    /// First copy, in milliseconds since 1970.
    pub first_copied_ms: u64,
    /// Bundle identifier of the source app.
    pub source_bundle_id: Option<String>,
    /// Name of the source app.
    pub source_name: Option<String>,
    /// Image width in pixels, when known.
    pub image_width: Option<u32>,
    /// Image height in pixels, when known.
    pub image_height: Option<u32>,
    /// Bytes of content.
    pub size_bytes: u64,
    /// When a sensitive item expires.
    pub sensitive_until_ms: Option<u64>,
    /// Whether text was cut to the limit.
    pub truncated: bool,
}

impl From<cy_engine::ItemSummary> for ItemSummary {
    fn from(summary: cy_engine::ItemSummary) -> Self {
        let (source_bundle_id, source_name) = summary
            .source
            .map_or((None, None), |app| (Some(app.bundle_id), Some(app.name)));
        Self {
            id: summary.id.to_string(),
            kind: summary.kind.into(),
            preview: summary.preview,
            pinned: summary.pinned,
            last_used_ms: summary.last_used.wall_ms(),
            first_copied_ms: summary.first_copied_ms,
            source_bundle_id,
            source_name,
            image_width: summary.image_size.map(|(width, _)| width),
            image_height: summary.image_size.map(|(_, height)| height),
            size_bytes: summary.size_bytes,
            sensitive_until_ms: summary.sensitive_until_ms,
            truncated: summary.truncated,
        }
    }
}

