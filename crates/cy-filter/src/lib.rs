//! Decides whether Supercy keeps a clipboard snapshot, and in which form.
//!
//! The rules run in a fixed order (design 01, section 2): concealed and transient markers,
//! ignored clipboard types, ignored apps (or the allow-list), recognizable content with the
//! per-type switches and size limits, ignore patterns, then sensitive-content detection.
//! [`decide`] is a pure function: a dropped snapshot leaves nothing behind but the reason.

mod capture;
mod markers;
mod patterns;
mod sensitive;

use std::collections::BTreeSet;

use cy_model::{ClipboardSnapshot, Representation, Sensitivity, SourceApp};

pub use markers::{Marker, find_marker};
pub use patterns::{MAX_PATTERN_LEN, MAX_PATTERNS, PatternError, PatternSet, validate_pattern};
pub use sensitive::detect_sensitive;

/// Default text limit: 1 MiB; longer text is cut.
pub const DEFAULT_MAX_TEXT_BYTES: usize = 1024 * 1024;
/// Default image limit: 5 MiB; larger images are not kept.
pub const DEFAULT_MAX_IMAGE_BYTES: usize = 5 * 1024 * 1024;
/// Default lifetime of sensitive items: 2 minutes.
pub const DEFAULT_SENSITIVE_TTL_MS: u64 = 2 * 60 * 1000;

/// What to keep. User-tunable; the defaults are the constants above.
#[derive(Clone, Debug, PartialEq, Eq)]
#[allow(
    clippy::struct_excessive_bools,
    reason = "user switches are naturally on/off values"
)]
pub struct FilterPolicy {
    /// Apps whose copies are never kept, by bundle identifier.
    pub ignored_apps: BTreeSet<String>,
    /// Allow-list mode: when set, only copies from these apps are kept.
    pub allowed_apps: Option<BTreeSet<String>>,
    /// Clipboard types that, when present, mean the copy is not kept.
    pub ignored_types: BTreeSet<String>,
    /// Text matching any of these patterns is not kept.
    pub ignore_patterns: PatternSet,
    /// Whether text, rich text and links are kept.
    pub record_text: bool,
    /// Whether images are kept.
    pub record_images: bool,
    /// Whether copied files (their references) are kept.
    pub record_files: bool,
    /// Longest text kept, in bytes.
    pub max_text_bytes: usize,
    /// Largest image kept, in bytes.
    pub max_image_bytes: usize,
    /// Whether sensitive-content detection runs.
    pub detect_sensitive: bool,
    /// How long sensitive items live.
    pub sensitive_ttl_ms: u64,
    /// Whether content marked auto-generated is kept.
    pub keep_auto_generated: bool,
}

impl Default for FilterPolicy {
    fn default() -> Self {
        Self {
            ignored_apps: BTreeSet::new(),
            allowed_apps: None,
            ignored_types: BTreeSet::new(),
            ignore_patterns: PatternSet::default(),
            record_text: true,
            record_images: true,
            record_files: true,
            max_text_bytes: DEFAULT_MAX_TEXT_BYTES,
            max_image_bytes: DEFAULT_MAX_IMAGE_BYTES,
            detect_sensitive: true,
            sensitive_ttl_ms: DEFAULT_SENSITIVE_TTL_MS,
            keep_auto_generated: false,
        }
    }
}

/// Why a snapshot was not kept.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DropReason {
    /// Marked concealed (passwords) by the source app.
    Concealed,
    /// Marked transient by the source app.
    Transient,
    /// Marked auto-generated and the policy does not keep those.
    AutoGenerated,
    /// Carries a clipboard type the user ignores.
    IgnoredType,
    /// Copied from an ignored app.
    IgnoredApp,
    /// Allow-list mode, and the app is not on the list.
    NotAllowedApp,
    /// Matches an ignore pattern.
    IgnoredPattern,
    /// Its kind of content is switched off (text, images or files).
    TypeDisabled,
    /// Nothing Supercy can keep.
    Unsupported,
    /// Only content above the size limits.
    TooLarge,
}

/// Content to keep.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Capture {
    /// The representations, in paste-preference order. Never empty.
    pub reps: Vec<Representation>,
    /// Whether text was cut to the limit.
    pub truncated: bool,
    /// The app it came from.
    pub source: Option<SourceApp>,
    /// Whether it is sensitive, and until when it lives.
    pub sensitivity: Sensitivity,
}

/// The result of [`decide`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum FilterDecision {
    /// Keep this content.
    Keep(Capture),
    /// Keep nothing.
    Drop(DropReason),
}

/// Decides what to keep from `snapshot` under `policy`.
#[must_use]
pub fn decide(snapshot: &ClipboardSnapshot, policy: &FilterPolicy) -> FilterDecision {
    if let Some(reason) = early_drop(snapshot, policy) {
        return FilterDecision::Drop(reason);
    }
    let built = match capture::build(&snapshot.entries, policy) {
        Ok(built) => built,
        Err(reason) => return FilterDecision::Drop(reason),
    };
    let ignored = built
        .reps
        .iter()
        .any(|rep| policy.ignore_patterns.is_match(&rep.search_text()));
    if ignored {
        return FilterDecision::Drop(DropReason::IgnoredPattern);
    }
    let sensitivity = sensitivity_of(&built.reps, snapshot.captured_at_ms, policy);
    FilterDecision::Keep(Capture {
        reps: built.reps,
        truncated: built.truncated,
        source: snapshot.front_app.clone(),
        sensitivity,
    })
}

/// Markers, ignored types and app rules: everything decided before reading the content.
fn early_drop(snapshot: &ClipboardSnapshot, policy: &FilterPolicy) -> Option<DropReason> {
    if let Some(reason) = marker_drop(snapshot, policy) {
        return Some(reason);
    }
    let ignored_type = snapshot.entries.iter().any(|entry| {
        policy
            .ignored_types
            .iter()
            .any(|t| t.eq_ignore_ascii_case(&entry.type_id))
    });
    if ignored_type {
        return Some(DropReason::IgnoredType);
    }
    let app = snapshot
        .front_app
        .as_ref()
        .map(|app| app.bundle_id.as_str());
    if let Some(allowed) = &policy.allowed_apps {
        return (!app.is_some_and(|id| allowed.contains(id))).then_some(DropReason::NotAllowedApp);
    }
    app.is_some_and(|id| policy.ignored_apps.contains(id))
        .then_some(DropReason::IgnoredApp)
}

fn marker_drop(snapshot: &ClipboardSnapshot, policy: &FilterPolicy) -> Option<DropReason> {
    match find_marker(&snapshot.entries)? {
        Marker::Concealed => Some(DropReason::Concealed),
        Marker::Transient => Some(DropReason::Transient),
        Marker::AutoGenerated if !policy.keep_auto_generated => Some(DropReason::AutoGenerated),
        Marker::AutoGenerated => None,
    }
}

fn sensitivity_of(reps: &[Representation], now_ms: u64, policy: &FilterPolicy) -> Sensitivity {
    if !policy.detect_sensitive {
        return Sensitivity::Normal;
    }
    reps.iter()
        .find_map(|rep| detect_sensitive(&rep.search_text()))
        .map_or(Sensitivity::Normal, |reason| Sensitivity::Sensitive {
            expires_at_ms: now_ms.saturating_add(policy.sensitive_ttl_ms),
            reason,
        })
}
