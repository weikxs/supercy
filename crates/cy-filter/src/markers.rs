//! Markers that source apps put on the clipboard to say "do not record this".

use cy_model::ClipEntry;

/// macOS, nspasteboard.org: the content is a password or other secret.
pub const MAC_CONCEALED: &str = "org.nspasteboard.ConcealedType";
/// macOS, nspasteboard.org: the content is on the clipboard only briefly.
pub const MAC_TRANSIENT: &str = "org.nspasteboard.TransientType";
/// macOS, nspasteboard.org: the content was generated, not copied by the user.
pub const MAC_AUTO_GENERATED: &str = "org.nspasteboard.AutoGeneratedType";
/// Windows: clipboard monitors must ignore this content.
pub const WIN_EXCLUDE_FROM_MONITORS: &str = "ExcludeClipboardContentFromMonitorProcessing";
/// Windows: a DWORD; 0 means "keep out of clipboard history".
pub const WIN_CAN_INCLUDE_IN_HISTORY: &str = "CanIncludeInClipboardHistory";
/// Linux (KDE and password managers such as KeePassXC): `secret` marks a password.
pub const LINUX_PASSWORD_HINT: &str = "x-kde-passwordManagerHint";

/// A "do not record" marker. Ordered from strongest to weakest.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Marker {
    /// A secret: never stored.
    Concealed,
    /// Short-lived content: never stored.
    Transient,
    /// Generated content: stored only if the policy says so.
    AutoGenerated,
}

/// The strongest marker on the clipboard, if any.
#[must_use]
pub fn find_marker(entries: &[ClipEntry]) -> Option<Marker> {
    entries.iter().filter_map(marker_of).min()
}

fn marker_of(entry: &ClipEntry) -> Option<Marker> {
    let type_id = entry.type_id.as_str();
    let is = |name: &str| type_id.eq_ignore_ascii_case(name);
    if is(MAC_CONCEALED) || is(WIN_EXCLUDE_FROM_MONITORS) {
        return Some(Marker::Concealed);
    }
    if is(MAC_TRANSIENT) {
        return Some(Marker::Transient);
    }
    if is(MAC_AUTO_GENERATED) {
        return Some(Marker::AutoGenerated);
    }
    if is(WIN_CAN_INCLUDE_IN_HISTORY) && !allows_history(entry) {
        return Some(Marker::Concealed);
    }
    if is(LINUX_PASSWORD_HINT) && says_secret(entry) {
        return Some(Marker::Concealed);
    }
    None
}

/// The Windows DWORD allows history only when present and non-zero; anything unreadable is
/// treated as "do not record", the safe side.
fn allows_history(entry: &ClipEntry) -> bool {
    entry
        .data
        .as_ref()
        .is_some_and(|data| !data.is_empty() && data.expose().iter().any(|byte| *byte != 0))
}

/// The hint marks a secret when its value is `secret`; a hint without readable data is treated
/// as a secret, the safe side.
fn says_secret(entry: &ClipEntry) -> bool {
    entry.data.as_ref().is_none_or(|data| {
        String::from_utf8_lossy(data.expose())
            .trim_matches(|c: char| c.is_whitespace() || c == '\0')
            .eq_ignore_ascii_case("secret")
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn text_entry() -> ClipEntry {
        ClipEntry::with_data("public.utf8-plain-text", b"demo-password-123".to_vec())
    }

    #[test]
    fn mac_markers_are_found() {
        for (name, marker) in [
            (MAC_CONCEALED, Marker::Concealed),
            (MAC_TRANSIENT, Marker::Transient),
            (MAC_AUTO_GENERATED, Marker::AutoGenerated),
        ] {
            assert_eq!(
                find_marker(&[text_entry(), ClipEntry::marker(name)]),
                Some(marker),
                "{name}"
            );
        }
    }

    #[test]
    fn the_strongest_marker_wins() {
        let entries = [
            ClipEntry::marker(MAC_AUTO_GENERATED),
            ClipEntry::marker(MAC_CONCEALED),
        ];

        assert_eq!(find_marker(&entries), Some(Marker::Concealed));
    }

    #[test]
    fn windows_exclude_format_conceals() {
        assert_eq!(
            find_marker(&[ClipEntry::marker(WIN_EXCLUDE_FROM_MONITORS)]),
            Some(Marker::Concealed)
        );
    }

    #[test]
    fn windows_history_dword_zero_or_missing_conceals_and_one_allows() {
        let zero = ClipEntry::with_data(WIN_CAN_INCLUDE_IN_HISTORY, vec![0, 0, 0, 0]);
        let missing = ClipEntry::marker(WIN_CAN_INCLUDE_IN_HISTORY);
        let one = ClipEntry::with_data(WIN_CAN_INCLUDE_IN_HISTORY, vec![1, 0, 0, 0]);

        assert_eq!(find_marker(&[zero]), Some(Marker::Concealed));
        assert_eq!(find_marker(&[missing]), Some(Marker::Concealed));
        assert_eq!(find_marker(&[one]), None);
    }

    #[test]
    fn linux_password_hint_secret_conceals_other_values_do_not() {
        let secret = ClipEntry::with_data(LINUX_PASSWORD_HINT, b"secret".to_vec());
        let unreadable = ClipEntry::marker(LINUX_PASSWORD_HINT);
        let other = ClipEntry::with_data(LINUX_PASSWORD_HINT, b"other".to_vec());

        assert_eq!(find_marker(&[secret]), Some(Marker::Concealed));
        assert_eq!(find_marker(&[unreadable]), Some(Marker::Concealed));
        assert_eq!(find_marker(&[other]), None);
    }

    #[test]
    fn markers_match_without_regard_to_ascii_case() {
        assert_eq!(
            find_marker(&[ClipEntry::marker("ORG.NSPASTEBOARD.CONCEALEDTYPE")]),
            Some(Marker::Concealed)
        );
    }

    #[test]
    fn plain_content_has_no_marker() {
        assert_eq!(find_marker(&[text_entry()]), None);
    }
}
