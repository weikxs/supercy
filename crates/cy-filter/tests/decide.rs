#[test]
fn sensitive_content_expires_after_the_ttl_unless_detection_is_off() {
    let pem = format!("-----BEGIN {}PRIVATE KEY-----", "EC ");
    let off = FilterPolicy {
        detect_sensitive: false,
        ..FilterPolicy::default()
    };

    let on = keep(decide(
        &snapshot(vec![text(&pem)]),
        &FilterPolicy::default(),
    ));
    let without = keep(decide(&snapshot(vec![text(&pem)]), &off));

    assert_eq!(
        on.sensitivity,
        Sensitivity::Sensitive {
            expires_at_ms: NOW_MS + DEFAULT_SENSITIVE_TTL_MS,
            reason: SensitiveReason::PrivateKey
        }
    );
    assert_eq!(without.sensitivity, Sensitivity::Normal);
}

#[test]
fn empty_and_unknown_clipboards_are_unsupported() {
    let unknown = vec![ClipEntry::with_data(
        "com.example.private-type",
        b"x".to_vec(),
    )];

    assert_eq!(
        decide(&snapshot(Vec::new()), &FilterPolicy::default()),
        FilterDecision::Drop(DropReason::Unsupported)
    );
    assert_eq!(
        decide(&snapshot(unknown), &FilterPolicy::default()),
        FilterDecision::Drop(DropReason::Unsupported)
    );
}

proptest! {
    #[test]
    fn concealed_content_is_never_kept_whatever_else_is_there(
        texts in proptest::collection::vec(".{0,64}", 0..4),
        marker_at in 0usize..5,
    ) {
        let mut entries: Vec<ClipEntry> = texts.iter().map(|t| text(t)).collect();
        let at = marker_at.min(entries.len());
        entries.insert(at, ClipEntry::marker("org.nspasteboard.ConcealedType"));

        prop_assert_eq!(decide(&snapshot(entries), &FilterPolicy::default()), FilterDecision::Drop(DropReason::Concealed));
    }

    #[test]
    fn decide_never_panics_on_arbitrary_entries(
        entries in proptest::collection::vec(("[a-zA-Z./-]{0,30}", proptest::collection::vec(any::<u8>(), 0..64)), 0..6),
    ) {
        let entries = entries.into_iter().map(|(type_id, data)| ClipEntry::with_data(type_id, data)).collect();

        let _ = decide(&snapshot(entries), &FilterPolicy::default());
    }
}
