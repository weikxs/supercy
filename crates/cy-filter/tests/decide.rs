#[test]
fn rich_text_keeps_html_rtf_and_plain_text() {
    let entries = vec![
        text("Demo"),
        ClipEntry::with_data("public.html", b"<b>Demo</b>".to_vec()),
        ClipEntry::with_data("public.rtf", b"{\\rtf1 Demo}".to_vec()),
    ];

    let capture = keep(decide(&snapshot(entries), &FilterPolicy::default()));

    assert!(matches!(
        &capture.reps[0],
        Representation::RichText {
            rtf: Some(_),
            html: Some(_),
            ..
        }
    ));
}

#[test]
fn a_copied_link_gets_a_url_representation_first() {
    let from_text = keep(decide(
        &snapshot(vec![text("https://example.com/a")]),
        &FilterPolicy::default(),
    ));
    let from_type = keep(decide(
        &snapshot(vec![
            ClipEntry::with_data("public.url", b"https://demo.example/b".to_vec()),
            text("Demo link"),
        ]),
        &FilterPolicy::default(),
    ));

    assert!(matches!(&from_text.reps[0], Representation::Url { .. }));
    assert_eq!(from_text.reps.len(), 2);
    assert_eq!(from_type.reps[0].search_text(), "https://demo.example/b");
}

#[test]
fn small_images_are_kept_and_oversized_images_are_too_large() {
    let small = ClipEntry::with_data("public.tiff", vec![1, 2, 3]);
    let unread = ClipEntry::oversized("public.png", 50 * 1024 * 1024);
    let policy = FilterPolicy {
        max_image_bytes: 2,
        ..FilterPolicy::default()
    };

    let kept = keep(decide(
        &snapshot(vec![small.clone()]),
        &FilterPolicy::default(),
    ));

    assert!(matches!(
        kept.reps[0],
        Representation::Image {
            format: ImageFormat::Tiff,
            ..
        }
    ));
    assert_eq!(
        decide(&snapshot(vec![small]), &policy),
        FilterDecision::Drop(DropReason::TooLarge)
    );
    assert_eq!(
        decide(&snapshot(vec![unread]), &FilterPolicy::default()),
        FilterDecision::Drop(DropReason::TooLarge)
    );
}

