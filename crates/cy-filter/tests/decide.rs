//! The filter's rules, end to end: one test per marker and per rule.

#![allow(
    clippy::unwrap_used,
    clippy::panic,
    reason = "test helpers fail loudly, like the tests themselves"
)]

use cy_filter::{
    Capture, DEFAULT_SENSITIVE_TTL_MS, DropReason, FilterDecision, FilterPolicy, PatternSet, decide,
};
use cy_model::{
    ClipEntry, ClipboardSnapshot, ImageFormat, Representation, SensitiveReason, Sensitivity,
    SourceApp,
};
use proptest::prelude::*;

const NOW_MS: u64 = 1_700_000_000_000;
const TEXT: &str = "public.utf8-plain-text";

fn snapshot(entries: Vec<ClipEntry>) -> ClipboardSnapshot {
    ClipboardSnapshot {
        entries,
        front_app: Some(SourceApp {
            bundle_id: "com.example.editor".into(),
            name: "Demo Editor".into(),
        }),
        captured_at_ms: NOW_MS,
    }
}

fn text(value: &str) -> ClipEntry {
    ClipEntry::with_data(TEXT, value.as_bytes().to_vec())
}

fn keep(decision: FilterDecision) -> Capture {
    match decision {
        FilterDecision::Keep(capture) => capture,
        FilterDecision::Drop(reason) => panic!("expected Keep, got Drop({reason:?})"),
    }
}

#[test]
fn plain_text_is_kept_with_its_source() {
    let capture = keep(decide(
        &snapshot(vec![text("Hello from Supercy")]),
        &FilterPolicy::default(),
    ));

    assert_eq!(capture.reps.len(), 1);
    assert_eq!(capture.reps[0].search_text(), "Hello from Supercy");
    assert_eq!(capture.source.unwrap().bundle_id, "com.example.editor");
    assert_eq!(capture.sensitivity, Sensitivity::Normal);
    assert!(!capture.truncated);
}

#[test]
fn every_concealing_marker_drops_the_content_on_every_platform() {
    let cases = [
        (
            ClipEntry::marker("org.nspasteboard.ConcealedType"),
            DropReason::Concealed,
        ),
        (
            ClipEntry::marker("org.nspasteboard.TransientType"),
            DropReason::Transient,
        ),
        (
            ClipEntry::marker("org.nspasteboard.AutoGeneratedType"),
            DropReason::AutoGenerated,
        ),
        (
            ClipEntry::marker("ExcludeClipboardContentFromMonitorProcessing"),
            DropReason::Concealed,
        ),
        (
            ClipEntry::with_data("CanIncludeInClipboardHistory", vec![0; 4]),
            DropReason::Concealed,
        ),
        (
            ClipEntry::with_data("x-kde-passwordManagerHint", b"secret".to_vec()),
            DropReason::Concealed,
        ),
    ];

    for (marker, reason) in cases {
        let decision = decide(
            &snapshot(vec![text("demo-password-123"), marker]),
            &FilterPolicy::default(),
        );
        assert_eq!(decision, FilterDecision::Drop(reason));
    }
}

