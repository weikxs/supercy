#![no_main]
//! The capture filter never panics on any clipboard content, and never keeps content that
//! carries a concealed or transient marker.
use cy_filter::{FilterDecision, FilterPolicy, decide};
use cy_model::{ClipEntry, ClipboardSnapshot};
use libfuzzer_sys::fuzz_target;

/// Clipboard types the filter knows, so the fuzzer reaches every branch.
const TYPES: &[&str] = &[
    "public.utf8-plain-text",
    "public.html",
    "public.rtf",
    "public.url",
    "public.png",
    "public.tiff",
    "public.file-url",
    "CF_UNICODETEXT",
    "HTML Format",
    "text/plain;charset=utf-8",
    "text/uri-list",
    "image/png",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "CanIncludeInClipboardHistory",
    "x-kde-passwordManagerHint",
    "com.example.unknown",
];

fuzz_target!(|input: (Vec<(u8, Option<Vec<u8>>, u32)>, u16)| {
    let (raw, max_text) = input;
    let entries: Vec<ClipEntry> = raw
        .into_iter()
        .map(|(kind, data, size)| {
            let type_id = TYPES[usize::from(kind) % TYPES.len()];
            match data {
                Some(bytes) => ClipEntry::with_data(type_id, bytes),
                None => ClipEntry::oversized(type_id, u64::from(size)),
            }
        })
        .collect();
    let hidden = entries.iter().any(|e| {
        e.type_id == "org.nspasteboard.ConcealedType"
            || e.type_id == "org.nspasteboard.TransientType"
    });
    let policy = FilterPolicy {
        max_text_bytes: usize::from(max_text),
        ..FilterPolicy::default()
    };

    let decision = decide(
        &ClipboardSnapshot {
            entries,
            front_app: None,
            captured_at_ms: 0,
        },
        &policy,
    );

    if hidden {
        assert!(
            matches!(decision, FilterDecision::Drop(_)),
            "hidden content was kept"
        );
    }
    if let FilterDecision::Keep(capture) = decision {
        assert!(!capture.reps.is_empty());
    }
});
